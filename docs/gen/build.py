#!/usr/bin/env python3
"""Generate the reference pages of the docs from the code.

Called by docs/hooks.py before every mkdocs build, and on its own with
``--check`` (``pixi run -e docs docs-check``) to list what is undocumented.

Generated pages (git-ignored; never edit them by hand):

- reference/cli.md        from the argparse parser in spimquant/run.py
- reference/templates.md  from ``templates:`` in spimquant/config/snakebids.yml
- reference/config.md     from the other top-level keys of that file and the
                          comments above them
- reference/outputs.md    from docs/generated/outputs.tsv
- reference/workflow.md   from docs/generated/rulegraph_*.dot
- examples/index.md       from docs/examples/manifest.yml

Hand-written text they use lives in docs/gen/descriptions.yml.
"""

import argparse
import csv
import re
import shutil
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

import yaml

DOCS = Path(__file__).resolve().parents[1]
REPO = DOCS.parent
CONFIG = REPO / "spimquant" / "config" / "snakebids.yml"
GEN = DOCS / "generated"
GEN_NOTE = (
    "<!-- Generated by docs/gen/build.py from {src}. Do not edit: "
    "changes are overwritten on the next build. -->\n\n"
)

# config keys that are not user settings, or have their own page
CONFIG_SKIP = {
    "analysis_levels",
    "targets_by_analysis_level",
    "pybids_inputs",
    "parse_args",
    "templates",
    "debug",
    "derivatives",
    "root",
    "work",
}


def load_descriptions():
    return yaml.safe_load((DOCS / "gen" / "descriptions.yml").read_text())


def write_if_changed(path, text):
    """Write only on change, so `mkdocs serve` does not rebuild in a loop."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def md_text(s):
    """Argparse/RST help text to markdown: ``x`` to `x`, and escape < and >
    outside code spans so that e.g. th<value> is not read as HTML."""
    s = re.sub(r"``(.+?)``", r"`\1`", s)
    parts = re.split(r"(`[^`]*`)", s)
    return "".join(
        p if p.startswith("`") else p.replace("<", "&lt;").replace(">", "&gt;")
        for p in parts
    )


# --- CLI --------------------------------------------------------------------


def get_parser():
    sys.path.insert(0, str(REPO))
    from spimquant.run import get_parser as _get

    return _get()


ACRONYMS = {"MRI", "QC", "LANTERN", "BIDS", "GPU"}


def section_title(title):
    """`DATASET QC (qc level)` -> `Dataset QC (qc level)`."""
    words = title.split(" ")
    out = [w if w in ACRONYMS or not w.isupper() else w.lower() for w in words]
    out[0] = out[0][0].upper() + out[0][1:]
    return " ".join(out)


def cli_page(desc):
    parser = get_parser()
    fmt = parser._get_formatter()
    cfg = yaml.safe_load(CONFIG.read_text())
    out = [
        GEN_NOTE.format(src="spimquant/run.py and the config"),
        "# Command-line reference\n",
    ]
    out.append(
        "```\nspimquant BIDS_DIR OUTPUT_DIR ANALYSIS_LEVEL [options]\n```\n\n"
        "Each option can also be set in a YAML file given with "
        "`--configfile`, under its config key. Options not listed here are passed to "
        "Snakemake (`--cores`, `--executor`, `-n`...; see `spimquant "
        "--help-snakemake`).\n"
    )
    out.append("## Analysis levels\n")
    out.append("| Level | What it does |\n|---|---|")
    for level in cfg["analysis_levels"]:
        text = desc["analysis_levels"].get(level, "")
        out.append(f"| `{level}` | {text} |")
    out.append("")
    groups = [g for g in parser._action_groups if g.title != "options"]
    groups += [g for g in parser._action_groups if g.title == "options"]
    for group in groups:
        actions = [
            a
            for a in group._group_actions
            if a.help != argparse.SUPPRESS and not isinstance(a, argparse._HelpAction)
        ]
        if not actions or group.title == "positional arguments":
            continue
        title = (
            "Other options" if group.title == "options" else section_title(group.title)
        )
        out.append(f"## {title}\n")
        if group.description:
            out.append(md_text(group.description) + "\n")
        for a in actions:
            long_flags = [f for f in a.option_strings if f.startswith("--")]
            name = long_flags[0]  # as written in the config
            anchor = name.lstrip("-").replace("-", "_")
            meta = ""
            if a.nargs != 0:
                meta = " " + (a.metavar or a.dest.upper())
                if a.nargs in ("+", "*"):
                    meta += " ..."
            out.append(f"### `{name}{meta}` {{ #{anchor} }}\n")
            others = [f for f in a.option_strings if f != name]
            help_text = fmt._expand_help(a) if a.help else ""
            out.append(md_text(" ".join(help_text.split())) + "\n")
            facts = []
            if a.choices:
                facts.append("Choices: " + ", ".join(f"`{c}`" for c in a.choices))
            if (
                a.default not in (None, False, [], argparse.SUPPRESS)
                and "default" not in help_text.lower()
            ):
                facts.append(f"Default: `{a.default}`")
            if others:
                facts.append("Also: " + ", ".join(f"`{o}`" for o in others))
            facts.append(f"Config key: `{a.dest}`")
            if facts:
                out.append("<small>" + " · ".join(facts) + "</small>\n")
    return "\n".join(out) + "\n"


# --- templates --------------------------------------------------------------


def templates_page(desc):
    cfg = yaml.safe_load(CONFIG.read_text())
    out = [
        GEN_NOTE.format(src="templates: in spimquant/config/snakebids.yml"),
        "# Templates\n",
    ]
    out.append(
        "Templates and atlases available with `--template` (and `--via-template`, "
        "`--template-mri`). Remote files are downloaded on first use. To add "
        "one, add an entry under `templates:` in the config (or in your own "
        "`--configfile`).\n"
    )
    out.append(
        "| Template | Description | Atlases (`--atlas_segs`) | Brain mask | Source |"
    )
    out.append("|---|---|---|---|---|")
    for name, t in cfg["templates"].items():
        atlases = ", ".join(f"`{a}`" for a in (t.get("atlases") or {})) or "–"
        default = t.get("default_segs")
        if default:
            atlases += f" (default: {', '.join(default)})"
        anat = str(t.get("anat", ""))
        m = re.search(r"zenodo.org/records/(\d+)", anat)
        if m:
            src = f"[Zenodo {m.group(1)}](https://zenodo.org/records/{m.group(1)})"
        elif anat.startswith("http"):
            host = re.match(r"https?://([^/]+)", anat).group(1)
            src = f"[{host}]({anat.rsplit('/', 1)[0]})"
        else:
            src = "bundled"
        mask = "yes" if t.get("mask") else "–"
        text = " ".join(str(desc["templates"].get(name, "")).split())
        out.append(f"| `{name}` | {text} | {atlases} | {mask} | {src} |")
    return "\n".join(out) + "\n"


# --- config -----------------------------------------------------------------


def config_entries():
    """Top-level keys of the config with their description: the comment
    block above the key, or, for a key without one, a pointer to the key
    whose comment starts its block (keys not separated by a blank line)."""
    entries, comment, block_head = [], [], None
    for line in CONFIG.read_text().splitlines():
        if line.startswith("#"):
            comment.append(line.lstrip("#").strip())
        elif m := re.match(r"^([A-Za-z_][\w]*):", line):
            key = m.group(1)
            text = " ".join(c for c in comment if c)
            if text:
                block_head = key
            elif block_head:
                text = f"See `{block_head}`."
            entries.append((key, text))
            comment = []
        elif not line.strip():
            comment, block_head = [], None
    return entries


def config_page(desc):
    cfg = yaml.safe_load(CONFIG.read_text())
    cli_keys = {a.dest for a in get_parser()._actions}
    out = [
        GEN_NOTE.format(src="spimquant/config/snakebids.yml"),
        "# Configuration keys\n",
    ]
    out.append(
        "Settings that have no command-line option. Change them with your own "
        "YAML file, given with `--configfile my.yml`, which only needs the "
        "keys you change. Options in the [command-line reference](cli.md) can "
        "be set the same way, under their name with underscores.\n"
    )
    out.append("| Key | Default | Description |\n|---|---|---|")
    for key, comment in config_entries():
        if key in CONFIG_SKIP or key in cli_keys:
            continue
        val = yaml.safe_dump(cfg.get(key), default_flow_style=True, width=1e9).strip()
        val = val.removesuffix("...").strip()
        if len(val) > 60:
            val = val[:57] + "..."
        out.append(f"| `{key}` | `{val}` | {md_text(comment)} |")
    return "\n".join(out) + "\n"


# --- outputs ----------------------------------------------------------------


def read_outputs():
    with open(GEN / "outputs.tsv") as f:
        return [r for r in csv.DictReader(f, delimiter="\t") if r["temp"] == "no"]


def folder_of(path):
    parts = path.split("/")
    if parts[0].startswith("sub-"):
        return parts[1]
    if parts[0] == "qc":
        return "dataset-qc"
    return parts[0]


def suffix_key(path, keys):
    name = path.rsplit("/", 1)[-1]
    matches = [
        k
        for k in keys
        if name.endswith(k) and (len(name) == len(k) or name[-len(k) - 1] in "_.")
    ]
    return max(matches, key=len) if matches else None


def outputs_page(desc):
    scen = {
        s["name"]: s
        for s in yaml.safe_load((DOCS / "gen" / "scenarios.yml").read_text())[
            "scenarios"
        ]
    }
    rows = read_outputs()
    keys = [k for k in desc["outputs"] if "/" not in k]
    by_folder = defaultdict(lambda: defaultdict(list))
    for r in rows:
        by_folder[folder_of(r["path"])][suffix_key(r["path"], keys)].append(r)
    out = [
        GEN_NOTE.format(src="docs/generated/outputs.tsv (pixi run docs-introspect)"),
        "# Output files\n",
    ]
    out.append(
        "Every file a run leaves in the output directory, listed from the "
        "workflow itself (dry runs of the test dataset; temporary files are "
        "left out). In the names below:\n\n"
        "- `*_` stands for the entities of the input scan, e.g. "
        "`sub-01_ses-exvivo_sample-brain_acq-4x_`;\n"
        "- `{stain}`, `{template}`, `{atlas}` (`seg-`), `{level}`, "
        "`{seg_method}` and `{object_method}` (`desc-`, `obj-`) take the values "
        "of your run. Per-stain files carry the stain's methods; files that "
        "combine stains use each stain's primary methods and carry neither "
        "(see [Segmentation](../howto/segmentation.md#choosing-methods-per-stain));\n"
        "- `{label}` is `--group-stats-label` and `{contrast}` a pairwise "
        "contrast, e.g. `treatment+controlvsdrug`.\n\n"
        "Files marked *with ...* are only written with that option.\n"
    )
    order = list(desc["folders"].keys())
    for folder in sorted(by_folder, key=lambda f: order.index(f) if f in order else 99):
        title = folder if folder != "dataset-qc" else "qc (dataset QC level)"
        where = (
            f"sub-{{subject}}/{folder}/"
            if folder
            in (
                "micr",
                "parc",
                "seg",
                "vessels",
                "fibres",
                "tabular",
                "featuremap",
                "xfm",
                "qc",
                "anat",
            )
            else f"{folder}/"
        )
        if folder == "dataset-qc":
            where = "qc/"
        fid = re.sub(r"[^a-z0-9]+", "-", folder.lower()).strip("-")
        out.append(f"## `{where}` {{ #{fid} }}\n")
        out.append(" ".join(str(desc["folders"].get(folder, "")).split()) + "\n")
        for key, items in sorted(by_folder[folder].items(), key=lambda kv: str(kv[0])):
            text = desc["outputs"].get(f"{folder}/{key}", desc["outputs"].get(key, ""))
            text = " ".join(str(text).split())
            flags = {i["path"]: scen[i["scenario"]].get("flags") or "" for i in items}
            needs = set(flags.values())
            label = f"`{key}`" if key else "(undescribed)"
            anchor = re.sub(r"[^a-z0-9]+", "-", f"{folder}-{key}".lower()).strip("-")
            line = f'<a id="{anchor}"></a>**{label}** — {md_text(text)}'
            if "" not in needs:  # every pattern needs an option
                line += " *With " + ", ".join(f"`{n}`" for n in sorted(needs)) + ".*"
            out.append(line + "\n")
            names = {}
            for path, flag in flags.items():
                name = re.sub(
                    r"^sub-\{subject\}_sample-\{sample\}_acq-\{acq\}_",
                    "*_",
                    path.rsplit("/", 1)[-1],
                )
                names[name] = flag if "" in needs else ""
            width = max(len(n) for n in names)
            lines = [
                f"{n:<{width}}  # with {f}" if f else n
                for n, f in sorted(names.items())
            ]
            out.append("```\n" + "\n".join(lines) + "\n```\n")
    return "\n".join(out) + "\n"


# --- workflow graphs --------------------------------------------------------


def workflow_page(desc, img_dir):
    scen = yaml.safe_load((DOCS / "gen" / "scenarios.yml").read_text())["scenarios"]
    out = [
        GEN_NOTE.format(
            src="docs/generated/rulegraph_*.dot (pixi run docs-introspect)"
        ),
        "# Workflow graphs\n",
    ]
    out.append(
        "The rules each analysis level runs and how they depend on each other, "
        "from dry runs of the test dataset (`spimquant ... --rulegraph`). Each "
        "box is a rule, run once per subject, stain, atlas... as needed. Click "
        "a graph to open it full size. To draw the graph of your own run: "
        "`spimquant BIDS OUT participant [options] --rulegraph | dot -Tsvg > rules.svg`.\n"
    )
    have_dot = shutil.which("dot") is not None
    for s in scen:
        dot = GEN / f"rulegraph_{s['name']}.dot"
        if not dot.exists():
            continue
        nrules = len(re.findall(r"^\s*\d+\[", dot.read_text(), re.M))
        out.append(f"## {s['label']}\n")
        cmd = f"spimquant BIDS OUT {s.get('level', 'participant')}"
        if s.get("flags"):
            cmd += " " + s["flags"]
        out.append(f"`{cmd}`: {nrules} rules.\n")
        if have_dot:
            svg = img_dir / f"rulegraph_{s['name']}.svg"
            svg.parent.mkdir(parents=True, exist_ok=True)
            subprocess.run(["dot", "-Tsvg", str(dot), "-o", str(svg)], check=True)
            out.append(
                f"[![{s['label']} rule graph](img/{svg.name})](img/{svg.name})\n"
            )
        else:
            out.append("*(Graphviz `dot` not found: graph not drawn.)*\n")
    return "\n".join(out) + "\n"


# --- examples ---------------------------------------------------------------


def examples_page(desc):
    ex = DOCS / "examples"
    manifest = ex / "manifest.yml"
    out = [
        GEN_NOTE.format(
            src="docs/examples/manifest.yml (docs/gen/collect_examples.py)"
        ),
        "# Example outputs\n",
    ]
    if not manifest.exists():
        out.append(
            "No example outputs have been collected yet (see `docs/gen/collect_examples.py`).\n"
        )
        return "\n".join(out) + "\n"
    m = yaml.safe_load(manifest.read_text())
    out.append(" ".join(str(m.get("intro", "")).split()) + "\n")
    out.append("| | |\n|---|---|")
    for k in (
        "dataset",
        "resolution",
        "stains",
        "spimquant_version",
        "command",
        "collected",
    ):
        if m.get(k):
            v = m[k]
            v = f"`{v}`" if k in ("command", "spimquant_version") else v
            out.append(f"| {k.replace('_', ' ').capitalize()} | {v} |")
    out.append("")
    section = None
    for item in m["items"]:
        if item.get("section") != section:
            section = item.get("section")
            out.append(f"## {section}\n")
        out.append(f"### {item['title']}\n")
        if item.get("text"):
            out.append(" ".join(item["text"].split()) + "\n")
        f = item["file"]
        if f.endswith((".png", ".jpg", ".svg")):
            out.append(f"[![{item['title']}]({f})]({f})\n")
        elif f.endswith(".html"):
            out.append(
                f'<iframe src="{f}" style="width:100%;height:640px;border:1px solid #ddd" loading="lazy"></iframe>\n\n'
                f"[Open the report on its own page]({f})\n"
            )
        elif f.endswith(".md"):
            out.append((ex / f).read_text() + "\n")
        if item.get("source"):
            out.append(f"<small>Output file: `{item['source']}`</small>\n")
    return "\n".join(out) + "\n"


# --- driver -----------------------------------------------------------------


def generate():
    desc = load_descriptions()
    ref = DOCS / "reference"
    write_if_changed(ref / "cli.md", cli_page(desc))
    write_if_changed(ref / "templates.md", templates_page(desc))
    write_if_changed(ref / "config.md", config_page(desc))
    write_if_changed(ref / "outputs.md", outputs_page(desc))
    write_if_changed(ref / "workflow.md", workflow_page(desc, ref / "img"))
    write_if_changed(DOCS / "examples" / "index.md", examples_page(desc))


def check():
    """List what the hand-written descriptions are missing."""
    desc = load_descriptions()
    cfg = yaml.safe_load(CONFIG.read_text())
    problems = []
    for level in cfg["analysis_levels"]:
        if level not in desc["analysis_levels"]:
            problems.append(f"analysis level `{level}`: add it to analysis_levels")
    for name in cfg["templates"]:
        if name not in desc["templates"]:
            problems.append(f"template `{name}`: add it to templates")
    keys = [k for k in desc["outputs"] if "/" not in k]
    for r in read_outputs():
        folder = folder_of(r["path"])
        if folder not in desc["folders"]:
            problems.append(
                f"output folder `{folder}` ({r['path']}): add it to folders"
            )
        if suffix_key(r["path"], keys) is None:
            problems.append(
                f"output `{r['path']}` (rule {r['rule']}): add its suffix to outputs"
            )
    choices = set(get_parser()._option_string_actions["--template"].choices or [])
    spim_templates = {n for n, t in cfg["templates"].items() if t.get("atlases")}
    for n in sorted(choices - set(cfg["templates"])):
        problems.append(
            f"--template choice `{n}` has no entry under templates: in the config"
        )
    for n in sorted(spim_templates - choices):
        problems.append(f"template `{n}` has atlases but is not a --template choice")
    declared = cfg.get("parse_args_groups") or {}
    for name, arg in cfg["parse_args"].items():
        group = (arg or {}).get("group")
        if group is None:
            problems.append(f"option `{name}` has no `group:` in parse_args")
        elif group not in declared:
            problems.append(
                f"option `{name}`: group `{group}` is not in parse_args_groups"
            )
    for p in dict.fromkeys(problems):
        print("undocumented:", p)
    return 1 if problems else 0


if __name__ == "__main__":
    if "--check" in sys.argv:
        sys.exit(check())
    generate()
